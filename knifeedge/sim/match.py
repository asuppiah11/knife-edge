# ---------------------------------------------------------------------------
# Hidden tactical regimes
# ---------------------------------------------------------------------------
# own_att: multiplier on own goal intensity; opp_att: multiplier on the
# opponent's goal intensity while this regime is active (a low block concedes
# less; an open game concedes more). pressures: pressures per minute by this
# team out of possession. completion: additive change to own pass completion.
# opp_completion: additive change to opponent completion (press disrupts).
# tempo: multiplier on actions per minute. share: possession weight.
REGIMES: Dict[str, dict] = {
    "high_press": dict(own_att=1.10, opp_att=1.05, pressures=3.2, completion=-0.01, opp_completion=-0.05, tempo=1.10, share=1.05, shot_dist=16.5),
    "possession": dict(own_att=1.00, opp_att=0.88, pressures=1.4, completion=+0.04, opp_completion=0.00, tempo=0.95, share=1.35, shot_dist=17.5),
    "low_block_counter": dict(own_att=0.88, opp_att=0.82, pressures=0.9, completion=-0.03, opp_completion=+0.02, tempo=0.90, share=0.70, shot_dist=15.0),
    "open": dict(own_att=1.25, opp_att=1.25, pressures=2.0, completion=-0.02, opp_completion=-0.02, tempo=1.15, share=1.00, shot_dist=17.0),
    "game_management": dict(own_att=0.72, opp_att=0.85, pressures=1.1, completion=+0.03, opp_completion=0.00, tempo=0.80, share=1.15, shot_dist=19.0),
}
REGIME_NAMES = list(REGIMES.keys())

STYLE_PREFERENCE = {
    "high_press": {"high_press": 0.55, "possession": 0.15, "low_block_counter": 0.05, "open": 0.20, "game_management": 0.05},
    "possession": {"high_press": 0.15, "possession": 0.55, "low_block_counter": 0.05, "open": 0.15, "game_management": 0.10},
    "low_block_counter": {"high_press": 0.05, "possession": 0.10, "low_block_counter": 0.60, "open": 0.15, "game_management": 0.10},
    "balanced": {"high_press": 0.25, "possession": 0.25, "low_block_counter": 0.20, "open": 0.20, "game_management": 0.10},
}

# Position weights for who does what.
PASS_WEIGHTS = {"GK": 0.35, "RB": 1.2, "LB": 1.2, "CB": 1.3, "CM": 1.6, "RW": 1.0, "LW": 1.0, "ST": 0.7, "FB": 1.2, "W": 1.0}
SHOT_WEIGHTS = {"GK": 0.0, "RB": 0.15, "LB": 0.15, "CB": 0.25, "CM": 0.9, "RW": 1.8, "LW": 1.8, "ST": 3.0, "FB": 0.15, "W": 1.8}
SETPIECE_SHOT_WEIGHTS = {"GK": 0.0, "RB": 0.3, "LB": 0.3, "CB": 1.8, "CM": 0.8, "RW": 0.8, "LW": 0.8, "ST": 2.2, "FB": 0.3, "W": 0.8}
PRESS_WEIGHTS = {"GK": 0.0, "RB": 0.6, "LB": 0.6, "CB": 0.4, "CM": 1.4, "RW": 1.3, "LW": 1.3, "ST": 1.5, "FB": 0.6, "W": 1.3}
TACKLE_WEIGHTS = {"GK": 0.05, "RB": 1.3, "LB": 1.3, "CB": 1.4, "CM": 1.3, "RW": 0.6, "LW": 0.6, "ST": 0.4, "FB": 1.3, "W": 0.6}

SPRINT_MS = 7.0
# Reference finishing used when computing the mean hidden xG per regime pair (shooters are mostly forwards).
XBAR_REFERENCE_FINISHING = 0.58
_XBAR_CACHE: Dict[str, float] = {}


