class MatchSimulator:
    def __init__(self, league: League, home: Team, away: Team, seed: int, config: Optional[SimConfig] = None, match_id: Optional[str] = None, matchday: int = 1):
        self.league = league
        self.home = home
        self.away = away
        self.seed = seed
        self.cfg = config or SimConfig()
        self.rng = np.random.default_rng(seed)
        self.match_id = match_id or f"KE-{seed:06d}"
        self.matchday = matchday
        self.events: List[dict] = []
        self.truth_regimes: List[dict] = []
        self._regime_rec: Dict[str, dict] = {}
        self.truth_intensity: List[dict] = []
        self.truth_shots: List[dict] = []
        self._eid = 0
        self._possession_id = 0
        self.lam_h90, self.lam_a90 = league.expected_goals(home, away)
        self.periods: List[dict] = []
        self.ts = {
            home.team_id: _TeamState(team=home, regime=self._initial_regime(home)),
            away.team_id: _TeamState(team=away, regime=self._initial_regime(away)),
        }
        for st in self.ts.values():
            st.on_pitch = list(st.team.starters())
            st.bench = [p for p in st.team.players if not p.starter]
            st.subs_target = int(self.rng.integers(self.cfg.subs_min, self.cfg.subs_max + 1))
            mins = sorted(self.rng.integers(55, 88, size=st.subs_target).tolist())
            st.sub_minutes = mins
            for p in st.team.players:
                st.distance_m[p.player_id] = 0.0
                st.top_speed_ms[p.player_id] = 0.0
        # possession state carried across minutes
        self._ball_team: str = home.team_id
        self._ball_x: float = 52.5
        self._ball_y: float = 34.0
        self._ball_player: Optional[Player] = None
        self._poss_start_clock: float = 0.0
        self._poss_actions: int = 0
        self._poss_from_turnover_own_half: bool = False
        self._last_corner_clock: Dict[str, float] = {home.team_id: -1e9, away.team_id: -1e9}
        self._clock: float = 0.0
        self._period: int = 1
        self._period_start_clock: float = 0.0

    # ------------------------------------------------------------------ utils
    def _initial_regime(self, team: Team) -> str:
        prefs = STYLE_PREFERENCE[team.style]
        names = list(prefs.keys())
        return str(self.rng.choice(names, p=[prefs[n] for n in names]))

    def _opp(self, team_id: str) -> str:
        return self.away.team_id if team_id == self.home.team_id else self.home.team_id

    def _minute(self) -> int:
        secs_in_period = self._clock - self._period_start_clock
        return (0 if self._period == 1 else 45) + int(secs_in_period // 60)

    def _emit(self, team_id: str, etype: str, player: Optional[Player] = None, **kw) -> dict:
        self._eid += 1
        secs_in_period = self._clock - self._period_start_clock
        ev = {
            "event_id": self._eid,
            "match_id": self.match_id,
            "period": self._period,
            "minute": self._minute(),
            "second": int(secs_in_period % 60),
            "clock_s": round(self._clock, 1),
            "team_id": team_id,
            "player_id": player.player_id if player else None,
            "type": etype,
        }
        ev.update(kw)
        self.events.append(ev)
        return ev

    def _pick(self, players: List[Player], weights: Dict[str, float], exclude: Optional[Player] = None) -> Player:
        pool = [p for p in players if p is not exclude]
        w = np.array([max(weights.get(p.position, 0.5), 1e-6) for p in pool])
        return pool[int(self.rng.choice(len(pool), p=w / w.sum()))]

    # --------------------------------------------------------------- regimes
    def _maybe_switch_regimes(self, minute: int) -> None:
        for tid, st in self.ts.items():
            opp = self.ts[self._opp(tid)]
            lead = st.goals - opp.goals
            prefs = dict(STYLE_PREFERENCE[st.team.style])
            # state-dependent pull
            if minute >= 60 and lead >= 1:
                prefs["game_management"] += 0.45 + 0.1 * (minute - 60) / 30
                prefs["high_press"] *= 0.5
                prefs["open"] *= 0.5
            if minute >= 55 and lead <= -1:
                prefs["high_press"] += 0.35
                prefs["open"] += 0.25 + (0.2 if lead <= -2 else 0.0)
                prefs["game_management"] = 0.0
                prefs["low_block_counter"] *= 0.4
            if st.men < 11:
                prefs["low_block_counter"] += 0.4
                prefs["high_press"] *= 0.4
            names = list(prefs.keys())
            p = np.array([prefs[n] for n in names], dtype=float)
            p = p / p.sum()
            # stickiness
            if self.rng.random() < 0.70:
                new = st.regime
            else:
                new = str(self.rng.choice(names, p=p))
            if new != st.regime:
                self._regime_rec[tid]["end_min"] = minute
                self._open_regime(tid, new, minute)

    def _open_regime(self, tid: str, regime: str, minute: int) -> None:
        self.ts[tid].regime = regime
        rec = {"team_id": tid, "regime": regime, "start_min": minute, "end_min": None}
        self.truth_regimes.append(rec)
        self._regime_rec[tid] = rec

    # ------------------------------------------------------------- intensity
    def _state_mult(self, st: _TeamState, opp: _TeamState, minute: int) -> dict:
        lead = st.goals - opp.goals
        if lead >= 2:
            score = 0.82
        elif lead == 1:
            score = 0.90
        elif lead == 0:
            score = 1.0
        elif lead == -1:
            score = 1.22
        else:
            score = 1.30
        men = 1.0
        if st.men < 11:
            men *= 0.64 ** (11 - st.men)
        if opp.men < 11:
            men *= 1.30 ** (11 - opp.men)
        late = 1.0 + 0.10 * max(0.0, (minute - 75) / 15)  # late-game openness
        return {"score": score, "men": men, "late": late}

    def _true_mu(self, tid: str, minute: int) -> tuple[float, dict]:
        st, opp = self.ts[tid], self.ts[self._opp(tid)]
        base90 = self.lam_h90 if tid == self.home.team_id else self.lam_a90
        mult = self._state_mult(st, opp, minute)
        reg_own = REGIMES[st.regime]["own_att"]
        reg_opp = REGIMES[opp.regime]["opp_att"]
        mu = base90 / 90.0 * mult["score"] * mult["men"] * mult["late"] * reg_own * reg_opp
        return mu, {**mult, "regime_own": reg_own, "regime_opp": reg_opp, "base_per_90": base90}

    # -------------------------------------------------------------- shooting
    def _sample_shot_location(self, situation: str, regime: str, opp_regime: str) -> tuple[float, float]:
        if situation == "penalty":
            return 94.0, 34.0
        if situation == "set_piece":
            d = float(np.clip(self.rng.normal(11.0, 3.5), 5.5, 24.0))
        elif situation == "counter":
            d = float(np.clip(self.rng.normal(15.0, 5.0), 5.5, 30.0))
        else:
            centre = REGIMES[regime]["shot_dist"] + (2.0 if opp_regime == "low_block_counter" else 0.0)
            d = float(np.clip(self.rng.normal(centre + 1.5, 6.5), 5.5, 38.0))
        y_off = float(np.clip(self.rng.normal(0.0, 8.0 * min(1.0, d / 10.0)), -26.0, 26.0))
        x = PITCH_LENGTH - math.sqrt(max(d * d - y_off * y_off, 1.0))
        y = float(np.clip(34.0 + y_off, 0.5, PITCH_WIDTH - 0.5))
        return float(np.clip(x, 60.0, PITCH_LENGTH - 0.5)), y

    def _hidden_xg(self, public_xg: float, finishing: float, under_pressure: bool, situation: str, rng: Optional[np.random.Generator] = None) -> float:
        """Hidden generating probability: public xG plus shooter finishing and unobserved noise."""
        if situation == "penalty":
            return 0.76
        rng = rng or self.rng
        logit = math.log(public_xg / (1 - public_xg))
        logit += 0.55 * (finishing - 0.5)
        logit += float(rng.normal(0.0, 0.18))
        p = 1.0 / (1.0 + math.exp(-logit))
        return float(min(0.97, max(0.01, p)))

    def _xbar(self, regime: str, opp_regime: str) -> float:
        """Mean hidden xG of a shot under this regime pair (deterministic MC, cached globally)."""
        key = f"{regime}|{opp_regime}"
        if key not in _XBAR_CACHE:
            rng = np.random.default_rng(1234)
            saved = self.rng
            self.rng = rng
            vals = []
            for _ in range(3000):
                sit = "set_piece" if rng.random() < 0.12 else ("counter" if rng.random() < 0.12 else "open_play")
                x, y = self._sample_shot_location(sit, regime, opp_regime)
                head = rng.random() < (0.55 if sit == "set_piece" else 0.14)
                up = rng.random() < 0.45
                pub = xg_from_location(x, y, "head" if head else "right_foot", up, sit)
                vals.append(self._hidden_xg(pub, XBAR_REFERENCE_FINISHING, up, sit, rng=rng))
            self.rng = saved
            _XBAR_CACHE[key] = float(np.mean(vals))
        return _XBAR_CACHE[key]

    def _do_shot(self, tid: str, forced_situation: Optional[str] = None) -> dict:
        st, opp = self.ts[tid], self.ts[self._opp(tid)]
        # situation from context
        if forced_situation:
            situation = forced_situation
        elif self._clock - self._last_corner_clock[tid] < 25.0:
            situation = "set_piece"
        elif self._poss_from_turnover_own_half and self._poss_actions <= 4 and (self._clock - self._poss_start_clock) < 12.0:
            situation = "counter"
        else:
            situation = "open_play"
        x, y = self._sample_shot_location(situation, st.regime, opp.regime)
        weights = SETPIECE_SHOT_WEIGHTS if situation == "set_piece" else SHOT_WEIGHTS
        shooter = self._pick(st.on_pitch, weights)
        head = situation != "penalty" and self.rng.random() < (0.55 if situation == "set_piece" else 0.14)
        body = "head" if head else ("left_foot" if self.rng.random() < 0.3 else "right_foot")
        under_pressure = situation != "penalty" and self.rng.random() < (0.55 if opp.regime in ("low_block_counter", "game_management") else 0.42)
        public_xg = xg_from_location(x, y, body, under_pressure, situation)
        hidden = self._hidden_xg(public_xg, shooter.finishing, under_pressure, situation)
        dist, angle = shot_geometry(x, y)
        u = self.rng.random()
        if u < hidden:
            outcome = "goal"
        else:
            v = self.rng.random()
            outcome = "saved" if v < 0.44 else ("off_target" if v < 0.80 else ("blocked" if v < 0.95 else "post"))
        speed = float(np.clip(self.rng.normal(78 if body != "head" else 45, 14), 20, 125))
        assist_id = self.events[-1]["event_id"] if (self.events and self.events[-1]["type"] in ("pass", "carry") and self.events[-1]["team_id"] == tid) else None
        ev = self._emit(
            tid, "shot", shooter,
            x=round(x, 1), y=round(y, 1), end_x=round(PITCH_LENGTH, 1), end_y=round(float(np.clip(34 + self.rng.normal(0, 2.5), 30.5, 37.5)), 1),
            outcome=outcome, possession_id=self._possession_id, under_pressure=under_pressure,
            shot={"xg": round(public_xg, 3), "distance_m": round(dist, 1), "angle_rad": round(angle, 3), "body_part": body, "speed_kmh": round(speed, 1), "situation": situation, "assist_event_id": assist_id},
        )
        self.truth_shots.append({"event_id": ev["event_id"], "hidden_xg": round(hidden, 4), "shooter_finishing": round(shooter.finishing, 3)})
        self._clock += 2.0
        if outcome == "goal":
            st.goals += 1
            self._clock += float(self.rng.uniform(45, 75))  # celebration + restart
            self._restart(self._opp(tid), "kick_off", 52.5, 34.0)
        elif outcome == "saved":
            self._clock += float(self.rng.uniform(4, 10))
            gk = [p for p in opp.on_pitch if p.position == "GK"]
            self._set_ball(self._opp(tid), 6.0, 34.0, gk[0] if gk else None, new_possession=True)
        elif outcome == "off_target":
            self._clock += float(self.rng.uniform(12, 20))
            self._restart(self._opp(tid), "goal_kick", 5.5, 34.0)
        else:  # blocked / post
            r = self.rng.random()
            if r < 0.45:
                self._clock += float(self.rng.uniform(18, 30))
                self._last_corner_clock[tid] = self._clock
                cx, cy = 104.5, (0.5 if self.rng.random() < 0.5 else 67.5)
                taker = self._pick(st.on_pitch, PASS_WEIGHTS)
                self._emit(tid, "corner", taker, x=cx, y=cy, possession_id=self._possession_id)
                self._set_ball(tid, cx, cy, taker, new_possession=False)
            elif r < 0.75:
                self._set_ball(tid, max(60.0, x - 6.0), y, None, new_possession=False)
            else:
                self._set_ball(self._opp(tid), PITCH_LENGTH - x + 4.0, PITCH_WIDTH - y, None, new_possession=True)
        return ev

    # --------------------------------------------------------------- ball ops
    def _set_ball(self, tid: str, x: float, y: float, player: Optional[Player], new_possession: bool) -> None:
        if new_possession or tid != self._ball_team:
            self._possession_id += 1
            self._poss_start_clock = self._clock
            self._poss_actions = 0
            self._poss_from_turnover_own_half = (tid != self._ball_team) and x < 52.5
        self._ball_team = tid
        self._ball_x = float(np.clip(x, 0.5, PITCH_LENGTH - 0.5))
        self._ball_y = float(np.clip(y, 0.5, PITCH_WIDTH - 0.5))
        self._ball_player = player

    def _restart(self, tid: str, kind: str, x: float, y: float) -> None:
        st = self.ts[tid]
        taker = self._pick(st.on_pitch, PASS_WEIGHTS if kind != "goal_kick" else {"GK": 5.0})
        self._possession_id += 1
        self._poss_start_clock = self._clock
        self._poss_actions = 0
        self._poss_from_turnover_own_half = False
        self._ball_team = tid
        self._ball_x, self._ball_y, self._ball_player = x, y, taker
        self._emit(tid, kind, taker, x=x, y=y, possession_id=self._possession_id)

    def _turnover(self, to_tid: str, kind: str, x_in_loser_frame: float, y_in_loser_frame: float) -> None:
        """Opponent wins the ball. Coordinates arrive in the loser's frame."""
        nx = PITCH_LENGTH - x_in_loser_frame
        ny = PITCH_WIDTH - y_in_loser_frame
        st = self.ts[to_tid]
        if kind in ("tackle", "interception"):
            winner = self._pick(st.on_pitch, TACKLE_WEIGHTS)
            self._emit(to_tid, kind, winner, x=round(nx, 1), y=round(ny, 1), outcome="won", possession_id=self._possession_id + 1)
            self._clock += 1.5
            self._set_ball(to_tid, nx, ny, winner, new_possession=True)
        elif kind == "throw_in":
            self._clock += float(self.rng.uniform(8, 16))
            self._restart(to_tid, "throw_in", nx, 0.5 if ny < 34 else PITCH_WIDTH - 0.5)
        elif kind == "goal_kick":
            self._clock += float(self.rng.uniform(12, 20))
            self._restart(to_tid, "goal_kick", 5.5, 34.0)
        else:
            self._set_ball(to_tid, nx, ny, None, new_possession=True)

    # ---------------------------------------------------------------- texture
    def _texture_action(self) -> None:
        tid = self._ball_team
        st, opp = self.ts[tid], self.ts[self._opp(tid)]
        reg, oreg = REGIMES[st.regime], REGIMES[opp.regime]
        if self._ball_player is None:
            self._ball_player = self._pick(st.on_pitch, PASS_WEIGHTS)
        player = self._ball_player
        x, y = self._ball_x, self._ball_y
        self._poss_actions += 1

        # pressure by the opponent?
        press_rate = oreg["pressures"] / max(self.cfg.actions_per_min * reg["tempo"] * 0.5, 1.0)
        in_press_zone = x < 75.0
        under_pressure = in_press_zone and self.rng.random() < min(0.6, press_rate * (1.6 if opp.regime == "high_press" else 1.0))
        if under_pressure:
            presser = self._pick(opp.on_pitch, PRESS_WEIGHTS)
            self._emit(self._opp(tid), "pressure", presser, x=round(PITCH_LENGTH - x, 1), y=round(PITCH_WIDTH - y, 1), possession_id=self._possession_id, pressure={"duration_s": round(float(self.rng.uniform(0.8, 3.0)), 1)})

        # choose action
        r = self.rng.random()
        carry_p = 0.30 if x < 85 else 0.22
        if r < carry_p:
            # carry
            dist = float(np.clip(self.rng.exponential(7.0) + 1.5, 1.5, 45.0))
            ang = float(self.rng.normal(0.0, 0.7))  # radians from goalward
            end_x = float(np.clip(x + dist * math.cos(ang), 0.5, PITCH_LENGTH - 0.5))
            end_y = float(np.clip(y + dist * math.sin(ang), 0.5, PITCH_WIDTH - 0.5))
            dist = math.hypot(end_x - x, end_y - y)
            speed = float(player.top_speed_ms * self.rng.uniform(0.30, 0.92))
            if dist > 15 and self.rng.random() < 0.5 * player.pace:
                speed = float(player.top_speed_ms * self.rng.uniform(0.75, 0.98))
            duration = max(dist / max(speed, 0.5), 0.3)
            st.distance_m[player.player_id] += dist
            st.top_speed_ms[player.player_id] = max(st.top_speed_ms[player.player_id], speed)
            # tackle attempt?
            tackle_p = 0.05 + 0.06 * (oreg["pressures"] / 3.2) + (0.08 if under_pressure else 0.0)
            tackled = self.rng.random() < tackle_p
            self._emit(tid, "carry", player, x=round(x, 1), y=round(y, 1), end_x=round(end_x, 1), end_y=round(end_y, 1), outcome="fail" if tackled else "success", possession_id=self._possession_id, under_pressure=under_pressure, carry={"distance_m": round(dist, 1), "duration_s": round(duration, 1), "speed_ms": round(speed, 2), "sprint": bool(speed >= SPRINT_MS)})
            self._clock += duration
            if tackled:
                self._turnover(self._opp(tid), "tackle", end_x, end_y)
            else:
                self._ball_x, self._ball_y = end_x, end_y
            return

        # pass
        length = float(np.clip(self.rng.gamma(2.2, 7.5), 3.0, 60.0))
        forward_bias = 0.35 if x < 70 else 0.1
        if self.rng.random() < 0.55 + forward_bias:
            ang = float(self.rng.normal(0.0, 0.6))
        else:
            # lateral pass, biased towards the centre of the pitch and away from the touchline
            towards_centre = 1.0 if y < PITCH_WIDTH / 2 else -1.0
            side = towards_centre if self.rng.random() < 0.5 + 0.4 * abs(y - 34.0) / 34.0 else -towards_centre
            ang = float(self.rng.normal(side * math.pi / 2, 0.5))
        if st.regime == "low_block_counter" and x < 40 and self.rng.random() < 0.35:
            length = float(np.clip(self.rng.normal(45, 10), 25, 65))
            ang = float(self.rng.normal(0.0, 0.35))
        end_x = x + length * math.cos(ang)
        end_y = y + length * math.sin(ang)
        out_of_play = end_x > PITCH_LENGTH or end_x < 0 or end_y > PITCH_WIDTH or end_y < 0
        if out_of_play and self.rng.random() < 0.88:
            # players aim at team-mates on the pitch: pull the target back inside with a margin
            end_x = float(np.clip(end_x, 2.0, PITCH_LENGTH - 3.0))
            end_y = float(np.clip(end_y, 2.0, PITCH_WIDTH - 2.0))
            out_of_play = False
        end_x_c = float(np.clip(end_x, 0.5, PITCH_LENGTH - 0.5))
        end_y_c = float(np.clip(end_y, 0.5, PITCH_WIDTH - 0.5))
        diff = pass_difficulty(x, y, end_x_c, end_y_c, under_pressure)
        skill_adj = -0.18 * (player.passing - 0.5)
        p_fail = float(np.clip(diff + skill_adj - reg["completion"] - oreg["opp_completion"], 0.02, 0.95))
        failed = out_of_play or self.rng.random() < p_fail
        recipient = None if failed else self._pick(st.on_pitch, PASS_WEIGHTS, exclude=player)
        self._emit(tid, "pass", player, x=round(x, 1), y=round(y, 1), end_x=round(end_x_c, 1), end_y=round(end_y_c, 1), outcome="fail" if failed else "success", possession_id=self._possession_id, under_pressure=under_pressure, **{"pass": {"distance_m": round(math.hypot(end_x_c - x, end_y_c - y), 1), "forward_m": round(end_x_c - x, 1), "difficulty": round(diff, 3), "progressive": bool(is_progressive(x, end_x_c)), "into_final_third": bool(end_x_c >= 70 and x < 70), "recipient_id": recipient.player_id if recipient else None}})
        self._clock += float(self.rng.uniform(1.6, 3.6))
        if failed:
            if out_of_play:
                if end_x > PITCH_LENGTH:
                    self._turnover(self._opp(tid), "goal_kick", end_x_c, end_y_c)
                else:
                    self._turnover(self._opp(tid), "throw_in", end_x_c, end_y_c)
            else:
                kind = "interception" if self.rng.random() < 0.55 else "loose"
                self._turnover(self._opp(tid), kind, end_x_c, end_y_c)
        else:
            self._ball_x, self._ball_y, self._ball_player = end_x_c, end_y_c, recipient

    def _build_up_to_shot(self, tid: str) -> None:
        """Make sure `tid` has the ball near goal, with 1-3 preparatory actions."""
        if self._ball_team != tid:
            x_in_loser = float(self.rng.uniform(25, 70))
            y_in_loser = float(self.rng.uniform(10, 58))
            kind = "interception" if self.rng.random() < 0.5 else "tackle"
            self._turnover(tid, kind, x_in_loser, y_in_loser)
        n = int(self.rng.integers(1, 4))
        st = self.ts[tid]
        for i in range(n):
            if self._ball_team != tid:
                self._set_ball(tid, float(self.rng.uniform(55, 80)), float(self.rng.uniform(10, 58)), None, new_possession=True)
            player = self._ball_player or self._pick(st.on_pitch, PASS_WEIGHTS)
            x, y = self._ball_x, self._ball_y
            target_x = min(PITCH_LENGTH - 8.0, x + float(self.rng.uniform(6, 22)))
            target_y = float(np.clip(y + self.rng.normal(0, 9), 6, PITCH_WIDTH - 6))
            if self.rng.random() < 0.65:
                recipient = self._pick(st.on_pitch, PASS_WEIGHTS, exclude=player)
                diff = pass_difficulty(x, y, target_x, target_y, False)
                self._poss_actions += 1
                self._emit(tid, "pass", player, x=round(x, 1), y=round(y, 1), end_x=round(target_x, 1), end_y=round(target_y, 1), outcome="success", possession_id=self._possession_id, under_pressure=False, **{"pass": {"distance_m": round(math.hypot(target_x - x, target_y - y), 1), "forward_m": round(target_x - x, 1), "difficulty": round(diff, 3), "progressive": bool(is_progressive(x, target_x)), "into_final_third": bool(target_x >= 70 and x < 70), "recipient_id": recipient.player_id}})
                self._clock += float(self.rng.uniform(1.6, 3.2))
                self._ball_player = recipient
            else:
                dist = math.hypot(target_x - x, target_y - y)
                speed = float(player.top_speed_ms * self.rng.uniform(0.55, 0.98))
                st.distance_m[player.player_id] += dist
                st.top_speed_ms[player.player_id] = max(st.top_speed_ms[player.player_id], speed)
                self._poss_actions += 1
                self._emit(tid, "carry", player, x=round(x, 1), y=round(y, 1), end_x=round(target_x, 1), end_y=round(target_y, 1), outcome="success", possession_id=self._possession_id, under_pressure=False, carry={"distance_m": round(dist, 1), "duration_s": round(dist / speed, 1), "speed_ms": round(speed, 2), "sprint": bool(speed >= SPRINT_MS)})
                self._clock += dist / speed
            self._ball_x, self._ball_y = target_x, target_y

    # ------------------------------------------------------------ discipline
    def _maybe_foul(self, minute: int) -> None:
        if self.rng.random() >= self.cfg.foul_rate_per_min:
            return
        # fouling team: usually the team out of possession
        tid = self._opp(self._ball_team) if self.rng.random() < 0.75 else self._ball_team
        st = self.ts[tid]
        fouler = self._pick(st.on_pitch, TACKLE_WEIGHTS)
        fx = float(np.clip(self.rng.normal(45, 20), 2, 103))
        fy = float(np.clip(self.rng.normal(34, 14), 1, 67))
        self._emit(tid, "foul", fouler, x=round(fx, 1), y=round(fy, 1), possession_id=self._possession_id)
        self._clock += float(self.rng.uniform(10, 25))
        card = None
        u = self.rng.random()
        if fouler.player_id in st.booked and u < self.cfg.second_yellow_per_foul_if_booked:
            card = "second_yellow"
        elif u < self.cfg.straight_red_per_foul:
            card = "red"
        elif u < self.cfg.straight_red_per_foul + self.cfg.yellow_per_foul:
            card = "yellow"
        if card:
            self._emit(tid, "card", fouler, x=round(fx, 1), y=round(fy, 1), card={"colour": card})
            if card == "yellow":
                st.booked.add(fouler.player_id)
            else:
                st.sent_off.add(fouler.player_id)
                st.on_pitch = [p for p in st.on_pitch if p.player_id != fouler.player_id]
                st.men -= 1
        # free kick to the fouled team
        victim_tid = self._opp(tid)
        vx = PITCH_LENGTH - fx
        vy = PITCH_WIDTH - fy
        taker = self._pick(self.ts[victim_tid].on_pitch, PASS_WEIGHTS)
        self._set_ball(victim_tid, vx, vy, taker, new_possession=True)

    def _maybe_substitute(self, minute: int) -> None:
        for tid, st in self.ts.items():
            while st.subs_made < st.subs_target and st.sub_minutes and st.sub_minutes[0] <= minute and st.bench:
                st.sub_minutes.pop(0)
                outfield = [p for p in st.on_pitch if p.position != "GK"]
                if not outfield:
                    break
                out = outfield[int(self.rng.integers(len(outfield)))]
                # prefer a bench player of a compatible position
                compat = {"RB": "FB", "LB": "FB", "RW": "W", "LW": "W"}.get(out.position, out.position)
                cands = [p for p in st.bench if p.position == compat] or [p for p in st.bench if p.position != "GK"]
                if not cands:
                    break
                inc = cands[0]
                st.bench.remove(inc)
                st.on_pitch = [p for p in st.on_pitch if p.player_id != out.player_id] + [inc]
                st.subs_made += 1
                self._emit(tid, "substitution", inc, substitution={"player_in": inc.player_id, "player_out": out.player_id})
                self._clock += float(self.rng.uniform(15, 30))
                if self._ball_player is out:
                    self._ball_player = None

    # ------------------------------------------------------------------ run
    def run(self) -> "MatchSimulator":
        for tid, st in self.ts.items():
            self._open_regime(tid, st.regime, 0)
        for period in (1, 2):
            self._period = period
            self._period_start_clock = self._clock
            stoppage = int(self.rng.integers(60, 200)) if period == 1 else int(self.rng.integers(150, 400))
            length = self.cfg.regulation_half_s + stoppage
            self.periods.append({"period": period, "regulation_s": self.cfg.regulation_half_s, "stoppage_s": stoppage})
            self._emit(self.home.team_id if period == 1 else self.away.team_id, "period_start")
            self._restart(self.home.team_id if period == 1 else self.away.team_id, "kick_off", 52.5, 34.0)
            end_clock = self._period_start_clock + length
            while self._clock < end_clock - 0.5:
                minute = self._minute()
                minute_end = self._period_start_clock + ((minute - (0 if period == 1 else 45)) + 1) * 60.0
                minute_end = min(minute_end, end_clock)
                if minute % self.cfg.regime_switch_min == 0 and minute > 0 and (not self.truth_intensity or self.truth_intensity[-1]["minute"] != minute):
                    self._maybe_switch_regimes(minute)
                # intensities for this minute
                mu_h, parts_h = self._true_mu(self.home.team_id, minute)
                mu_a, parts_a = self._true_mu(self.away.team_id, minute)
                self.truth_intensity.append({"minute": minute, "period": period, "mu_home": round(mu_h, 5), "mu_away": round(mu_a, 5), "regime_home": self.ts[self.home.team_id].regime, "regime_away": self.ts[self.away.team_id].regime, "parts_home": parts_h, "parts_away": parts_a, "score": [self.ts[self.home.team_id].goals, self.ts[self.away.team_id].goals]})
                # schedule shots within the minute
                sched: List[tuple[float, str, Optional[str]]] = []
                for tid, mu in ((self.home.team_id, mu_h), (self.away.team_id, mu_a)):
                    st, opp = self.ts[tid], self.ts[self._opp(tid)]
                    xbar = self._xbar(st.regime, opp.regime)
                    n = int(self.rng.poisson(mu / xbar))
                    for _ in range(n):
                        sched.append((float(self.rng.uniform(self._clock, minute_end)), tid, None))
                    if self.rng.random() < self.cfg.penalty_per_min:
                        sched.append((float(self.rng.uniform(self._clock, minute_end)), tid, "penalty"))
                sched.sort(key=lambda t: t[0])
                self._maybe_substitute(minute)
                self._maybe_foul(minute)
                # fill the minute
                guard = 0
                while self._clock < minute_end - 0.3 and guard < 400:
                    guard += 1
                    if sched and self._clock >= sched[0][0] - 0.01:
                        _, tid, forced = sched.pop(0)
                        if self.ts[tid].men >= 7:
                            if self.cfg.texture:
                                self._build_up_to_shot(tid)
                            else:
                                self._set_ball(tid, 85.0, 34.0, None, new_possession=True)
                            self._do_shot(tid, forced)
                        continue
                    if self.cfg.texture:
                        self._texture_action()
                    else:
                        # fast mode: jump to the next scheduled shot or the end of the minute
                        self._clock = sched[0][0] if sched else minute_end
                # unfilled scheduled shots (e.g. after a goal ate the minute) are dropped: intensity is per-minute, so this
                # slightly undershoots mu after goals; recorded in truth via realised shots.
                if self._clock < minute_end:
                    self._clock = minute_end
            self._emit(self.home.team_id, "half_end")
        for r in self.truth_regimes:
            if r["end_min"] is None:
                r["end_min"] = self._minute()
        return self

    # ----------------------------------------------------------------- output
    def match_header(self) -> dict:
        return {
            "match_id": self.match_id,
            "seed": self.seed,
            "competition": "Knife-Edge Synthetic League",
            "matchday": self.matchday,
            "kickoff_iso": "2026-01-01T15:00:00Z",
            "home": self.home.public(),
            "away": self.away.public(),
            "lineups": {self.home.team_id: [p.public() for p in self.home.players], self.away.team_id: [p.public() for p in self.away.players]},
            "score": {"home": self.ts[self.home.team_id].goals, "away": self.ts[self.away.team_id].goals},
            "periods": self.periods,
            "provenance": {"generator": "knifeedge.sim.match.MatchSimulator", "version": GENERATOR_VERSION, "statement": PROVENANCE_STATEMENT},
        }

    def truth(self) -> dict:
        return {
            "match_id": self.match_id,
            "seed": self.seed,
            "pre_match": {"lam_home_90": round(self.lam_h90, 4), "lam_away_90": round(self.lam_a90, 4)},
            "strengths": {
                self.home.team_id: {"attack": round(self.home.attack, 4), "defence": round(self.home.defence, 4), "style": self.home.style},
                self.away.team_id: {"attack": round(self.away.attack, 4), "defence": round(self.away.defence, 4), "style": self.away.style},
            },
            "regimes": self.truth_regimes,
            "intensity_per_min": self.truth_intensity,
            "shots": self.truth_shots,
            "player_physical": {tid: {"distance_m": {k: round(v, 1) for k, v in st.distance_m.items()}, "top_speed_ms": {k: round(v, 2) for k, v in st.top_speed_ms.items()}} for tid, st in self.ts.items()},
        }

    def write(self, out_dir: Path) -> Path:
        out_dir = Path(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "match.json").write_text(json.dumps(self.match_header(), indent=2))
        with (out_dir / "events.jsonl").open("w") as f:
            for ev in self.events:
                f.write(json.dumps(ev) + "\n")
        (out_dir / "truth.json").write_text(json.dumps(self.truth(), indent=2))
        return out_dir


def simulate_match(seed: int, league: Optional[League] = None, home_idx: Optional[int] = None, away_idx: Optional[int] = None, config: Optional[SimConfig] = None, matchday: int = 1) -> MatchSimulator:
    league = league or build_league()
    rng = np.random.default_rng(seed + 991)
    if home_idx is None or away_idx is None:
        h, a = rng.choice(len(league.teams), size=2, replace=False)
        home_idx, away_idx = int(h), int(a)
    sim = MatchSimulator(league, league.teams[home_idx], league.teams[away_idx], seed=seed, config=config, matchday=matchday)
    return sim.run()
