"""Event-level synthetic match generator with hidden truth.

Design
------
* Goals are driven by a hidden per-minute intensity for each team
  (``mu = base_rate/90 * score_state * men_state * regime_own * regime_opp``).
  Each minute, the number of shots is Poisson(mu / xbar) where ``xbar`` is the
  mean hidden xG of a shot under the current regime, so E[goals] == mu exactly.
* Texture (passes, carries, pressures, tackles, dead balls) is generated
  around those shots from possession sequences whose tempo, completion and
  share depend on each team's hidden tactical regime.
* The engine only sees ``events.jsonl`` and ``match.json``. ``truth.json``
  holds the regimes, the intensities and the hidden xG per shot so model
  calibration can be measured honestly.

Nothing here reads real data. Clubs, players and matches are invented.
"""

